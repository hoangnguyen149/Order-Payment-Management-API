#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
if [[ ${1:-} == --help || ${1:-} == -h ]]; then
  echo 'Usage: bash scripts/run-sql-lab.sh [order-count: 100000..1000000]'
  echo 'Seeds demo history and benchmarks in the dedicated local OrderPaymentBenchmark database.'
  echo 'Start SQL first: docker compose --env-file .env up -d sqlserver'
  exit 0
fi
[[ $# -le 1 ]] || { echo 'Expected at most one order-count argument.' >&2; exit 2; }
task_order_count=${1:-100000}
[[ $task_order_count =~ ^[0-9]{6,7}$ ]] && (( 10#$task_order_count >= 100000 && 10#$task_order_count <= 1000000 )) || {
  echo 'order-count must be an integer between 100000 and 1000000.' >&2
  exit 2
}
[[ -f .env ]] || { echo 'Run bash scripts/init-dev-env.sh first.' >&2; exit 1; }
# Only source the trusted local file generated by init-dev-env.sh; never print its values.
set -a
source .env
set +a
export ConnectionStrings__DefaultConnection="Server=localhost,1433;Database=OrderPaymentBenchmark;User Id=sa;Password=$MSSQL_SA_PASSWORD;Encrypt=True;TrustServerCertificate=True"
dotnet run --project tools/OrderPayment.Tools -c Release -- seed --orders "$task_order_count" --allow-demo-data
dotnet run --project tools/OrderPayment.Tools -c Release -- benchmark --output artifacts/sql-tuning --allow-benchmark
